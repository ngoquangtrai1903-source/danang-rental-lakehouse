CREATE EXTENSION IF NOT EXISTS postgis;

CREATE SCHEMA IF NOT EXISTS ops;
CREATE SCHEMA IF NOT EXISTS silver;
CREATE SCHEMA IF NOT EXISTS gold;

CREATE TABLE IF NOT EXISTS ops.bronze_batches (
    batch_id UUID PRIMARY KEY,
    source TEXT NOT NULL,
    record_count INTEGER NOT NULL CHECK (record_count >= 0),
    indexed_count INTEGER NOT NULL CHECK (indexed_count >= 0),
    manifest_key TEXT NOT NULL,
    manifest_sha256 CHAR(64) NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('indexed', 'orphaned')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ops.bronze_payload_index (
    source TEXT NOT NULL,
    list_id TEXT NOT NULL,
    payload_format TEXT NOT NULL CHECK (payload_format IN ('json', 'html')),
    source_url TEXT,
    scraped_at TIMESTAMPTZ NOT NULL,
    batch_id UUID NOT NULL REFERENCES ops.bronze_batches(batch_id),
    object_key TEXT NOT NULL,
    record_index INTEGER NOT NULL CHECK (record_index >= 0),
    object_sha256 CHAR(64) NOT NULL,
    manifest_key TEXT NOT NULL,
    manifest_sha256 CHAR(64) NOT NULL,
    indexed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (source, list_id)
);
CREATE INDEX IF NOT EXISTS ix_bronze_payload_index_object
    ON ops.bronze_payload_index (object_key);
CREATE INDEX IF NOT EXISTS ix_bronze_payload_index_batch
    ON ops.bronze_payload_index (batch_id);

CREATE TABLE IF NOT EXISTS silver.listings (
    source TEXT NOT NULL,
    list_id TEXT NOT NULL,
    posted_date TEXT,
    price_vnd DOUBLE PRECISION,
    size_m2 DOUBLE PRECISION,
    price_per_m2_vnd DOUBLE PRECISION,
    furnishing_status TEXT,
    rooms TEXT,
    category_name TEXT,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    ward_name TEXT,
    street_name TEXT,
    street_number TEXT,
    subject TEXT,
    body TEXT,
    url TEXT,
    listing_type TEXT,
    scraped_at TEXT,
    PRIMARY KEY (source, list_id)
);

CREATE TABLE IF NOT EXISTS silver.merged (
    LIKE silver.listings INCLUDING ALL
);

CREATE TABLE IF NOT EXISTS silver.geocoded (
    LIKE silver.listings INCLUDING ALL
);

CREATE TABLE IF NOT EXISTS silver.geocode_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    list_id TEXT,
    source_address_query TEXT,
    matched_address TEXT,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    arcgis_score DOUBLE PRECISION,
    status TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

